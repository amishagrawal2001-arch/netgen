"""v0.5.171: shared HTML-report builder for the admin portal.

Operator: "also allow user to generate report for admin portal
http://san-hp-srv06:5050/admin"

Mirrors the RDMA-session report (utils/rdma_report.py) but for
the server-side admin state. One-click "Export Report" produces
a self-contained HTML file capturing:

  * Host: hostname, kernel, uptime, server version
  * Health: DPDK installed? IOMMU? VFIO modules? Hugepages?
            tx_worker present? Tools (ip, ethtool, ibv_devinfo,
            perftest, dpdk-devbind)
  * Network interfaces: each iface with MAC, IP, speed, MTU,
                       driver, NUMA, PCIe Gen, NIC model
  * RDMA HCAs: each HCA with link rate, MTU, state, PCIe Gen,
              NUMA, IP, driver, vendor, FW, first GID
  * DPDK bind history: timestamps + per-port driver
  * Orphan workers: any untracked tx/rx_worker processes
  * Hugepages: per-NUMA allocation

The output is self-contained (inline CSS, no external assets).
Operators can email / archive / attach to bug reports as-is.

Why separate from the diag_bundle endpoint?
  * diag_bundle = tar.gz of raw artefacts (lspci, ethtool dumps,
    journal slices) for engineering deep-dives.
  * This report = human-readable rendered HTML for sharing /
    archival / quick scan during incident triage.
"""
from __future__ import annotations

from html import escape
from typing import Any, Dict, List, Optional


def build_admin_report_html(
    *,
    snapshot: Dict[str, Any],
    generated_at: str,
    server_version: Optional[str] = None,
) -> str:
    """Render the full HTML document. `snapshot` is a merged dict
    of the data from /api/admin/health + /api/interfaces +
    /api/dpdk/status + /api/rdma/devices + /api/admin/bind_history
    + /api/streams/orphans. The endpoint fetches them via Flask
    test_client and hands the merged result here.

    `generated_at` is the server-side wall-clock at export time
    (caller-provided so the function stays pure / testable).
    `server_version` is the netgen version string (best-effort —
    e.g. from /api/health). Renders as `—` when missing.
    """
    head = _render_head()
    intro = _render_intro(snapshot, generated_at, server_version)
    body = (
        _render_health_section(snapshot)
        + _render_tools_section(snapshot)
        + _render_hugepages_section(snapshot)
        + _render_interfaces_section(snapshot)
        + _render_rdma_section(snapshot)
        + _render_bind_history_section(snapshot)
        + _render_orphans_section(snapshot)
    )
    footer = (
        "<footer>Generated by netgen admin portal. "
        "Self-contained HTML — safe to archive or attach to bug "
        "reports.</footer>"
    )
    return (
        f"<!DOCTYPE html>\n<html lang='en'><head>{head}</head>"
        f"<body><main class='container'>{intro}{body}{footer}</main>"
        f"</body></html>"
    )


