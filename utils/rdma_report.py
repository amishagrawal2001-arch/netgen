def _first_port(dev: Dict[str, Any]) -> Dict[str, Any]:
    ports = dev.get("ports") or []
    if ports and isinstance(ports[0], dict):
        return ports[0]
    return {}


def _first_gid(port: Dict[str, Any]) -> str:
    gids = port.get("gids") or []
    if not gids:
        return "—"
    # Truncate the long zero-padded form for readability — operator
    # cares about the prefix more than the host portion.
    g = str(gids[0])
    if len(g) > 24:
        return g[:19] + "…"
    return g


def _shorten_rate(rate: Optional[str]) -> str:
    """`/sys` rate is verbose, e.g. "100 Gb/sec (4X EDR)". Strip
    the speed-class suffix — operator cares about the headline
    "100 Gb/sec" in a table cell."""
    if not rate:
        return "—"
    s = str(rate).strip()
    # Drop the trailing "(4X EDR)" classifier if present.
    open_paren = s.find("(")
    if open_paren > 0:
        s = s[:open_paren].strip()
    return s or "—"


