def _render_run_section(idx: int, run: Dict[str, Any]) -> str:
    head = (
        f"<div class='run-head'>"
        f"<h2>Run #{idx + 1}"
        f" &middot; <span class='pill'>{escape(run.get('kind') or '?')}</span>"
        f" &middot; {escape(run.get('test') or '?')}</h2>"
        f"<span class='timestamp'>started at "
        f"{escape(run.get('started_at') or '?')}</span>"
        f"</div>"
    )
    headline = _render_headline(run)
    params = _render_params(run.get("params") or {})
    endpoints = _render_endpoints(
        run.get("endpoints") or {},
        run.get("endpoint_details") or [],
    )
    rows = _render_rows_table(
        run.get("rows") or [],
        run.get("summary") or None,
    )
    # v0.5.177: RFC 2544-style latency-vs-size curve. Appended when
    # the run carries `lat_sweep` (Spirent/Ixia-style). Empty string
    # for single-size runs so the legacy layout is unchanged.
    sweep_section = _render_lat_sweep_section(
        run.get("lat_sweep") or [],
        run.get("params") or {},
    )
    return (
        f"<section class='run-card'>"
        f"{head}{headline}"
        f"<h3>Parameters</h3>{params}"
        f"<h3>Endpoints</h3>{endpoints}"
        f"<h3>Results</h3>{rows}"
        f"{sweep_section}"
        f"</section>"
    )


_RATE_RE = re.compile(r"([0-9]+(?:\.[0-9]+)?)\s*Gb/sec",
                       re.IGNORECASE)


def _extract_line_rate_gbps(run: Dict[str, Any]) -> Optional[float]:
    """v0.5.170: pull a line-rate number from the endpoint details
    so we can show `BW / line-rate %` in the headline. Uses the
    SLOWEST endpoint as the cap — a 200 G ↔ 100 G run is capped
    at 100 G end-to-end. Returns None when we can't parse any
    endpoint's rate (legacy run_log entries without details)."""
    details = run.get("endpoint_details") or []
    rates: List[float] = []
    for d in details:
        dev = d.get("device") or {}
        ports = dev.get("ports") or []
        for p in ports:
            r = (p.get("rate") or "")
            m = _RATE_RE.search(r)
            if m:
                try:
                    rates.append(float(m.group(1)))
                    break
                except ValueError:
                    pass
    return min(rates) if rates else None


def _render_headline(run: Dict[str, Any]) -> str:
    """v0.5.167: key-result callout at the top of the run card.
    Pulls the headline BW + MsgRate from `summary` (or the lone
    `rows` entry for one-shot runs). Mirrors the dialog's post-run
    card so the export carries the same first-glance number.

    v0.5.170: appends `· X% of N G` line-rate efficiency when the
    endpoint table can supply a rate. Lets operators tell at a
    glance whether the test hit line rate (>90% = good).

    v0.5.180 (re-audit H-RE-3): dispatch on summary/row shape.
    Pre-fix this always rendered the BW headline; lat runs
    showed "— Gbps | — Mpps" in the green callout box despite
    the per-row table (in `_render_rows_table`) correctly
    dispatching to lat columns. The v0.5.179 fix landed the row
    dispatch but never updated the headline.
    """
    summary = run.get("summary") or {}
    rows = run.get("rows") or []
    # v0.5.180: lat vs BW dispatch — match `_render_rows_table`'s
    # `has_lat` predicate so the headline can't disagree with
    # the table below it.
    has_lat = (
        isinstance(summary.get("lat_avg_us"), (int, float))
        or any(isinstance(r.get("lat_avg_us"), (int, float))
               for r in rows)
    )
    if has_lat:
        return _render_lat_headline(run, summary, rows)

    # v0.5.181 followup: headline label reflects aggregation mode.
    # `sum_workers` / `sum_pairs` → "total across N", `avg_iterations`
    # → "average across N samples".
    mode = summary.get("aggregation_mode") or "avg_iterations"
    is_sum = mode in ("sum_workers", "sum_pairs")
    if (isinstance(summary.get("bw_avg_gbps"), (int, float))
            and summary.get("samples", 0) > 1):
        bw = float(summary["bw_avg_gbps"])
        n = int(summary["samples"])
        # v0.5.181 G-4: pairs_attempted is the sibling for the
        # sum_pairs mode (Topology) — same "N of M reported" honesty.
        if mode == "sum_pairs":
            attempted = summary.get("pairs_attempted")
        else:
            attempted = summary.get("workers_attempted")
        if is_sum:
            unit = ("workers" if mode == "sum_workers" else "pairs")
            if (isinstance(attempted, int) and attempted
                    and n < attempted):
                tail = f"total across {n} of {attempted} {unit}"
            else:
                tail = f"total across {n} {unit}"
        else:
            tail = f"average across {n} samples"
    else:
        bws = [r["bw_gbps"] for r in rows
               if isinstance(r.get("bw_gbps"), (int, float))]
        bw = max(bws) if bws else None
        # v0.5.182 NB-11: single-sample sum_workers / sum_pairs runs
        # (e.g. a 1-parallel-worker BW test) read `total X · final` —
        # inconsistent with the multi-worker phrase. Say
        # "total across 1 worker / pair" instead so the language
        # matches across worker counts.
        if is_sum and summary.get("samples") == 1:
            unit = ("worker" if mode == "sum_workers" else "pair")
            tail = f"total across 1 {unit}"
        else:
            tail = "final"
    if isinstance(summary.get("msgrate_avg_mpps"), (int, float)):
        mr: Optional[float] = float(summary["msgrate_avg_mpps"])
    else:
        mrs = [r["msgrate_mpps"] for r in rows
               if isinstance(r.get("msgrate_mpps"), (int, float))]
        mr = mrs[-1] if mrs else None
    if bw is None and mr is None:
        return ""
    bw_txt = f"{bw:.2f}" if isinstance(bw, float) else "—"
    mr_txt = f"{mr:.4f}" if isinstance(mr, float) else "—"
    extras = []
    if isinstance(summary.get("bw_min_gbps"), (int, float)) \
            and isinstance(summary.get("bw_max_gbps"), (int, float)) \
            and summary.get("samples", 0) > 1:
        extras.append(
            f"min {summary['bw_min_gbps']:.2f} / "
            f"max {summary['bw_max_gbps']:.2f} Gbps"
        )
    # v0.5.170: line-rate efficiency. Operators ask this every
    # run: "did we hit line rate?" Show the % up front.
    # v0.5.180 (re-audit M-RE-2): gate on `bw is float`. The lat
    # branch above already returns; the residual safety here is
    # for runs where `_render_headline` somehow ends up here with
    # neither bw nor lat data, where bw stays None and the calc
    # would multiply None.
    line_rate = _extract_line_rate_gbps(run)
    if isinstance(bw, float) and line_rate and line_rate > 0:
        pct = (bw / line_rate) * 100.0
        extras.append(
            f"{pct:.1f}% of {line_rate:g} G line rate")
    tail_html = escape(tail)
    if extras:
        tail_html += " &middot; " + " &middot; ".join(escape(b) for b in extras)
    return (
        f"<div class='headline'>"
        f"<span class='num'>{bw_txt}</span>"
        f"<span class='unit'> Gbps</span>"
        f"<span class='sep'>|</span>"
        f"<span class='num mr'>{mr_txt}</span>"
        f"<span class='unit'> Mpps</span>"
        f"<span class='tail'>&middot; {tail_html}</span>"
        f"</div>"
    )


def _render_lat_headline(
    run: Dict[str, Any],
    summary: Dict[str, Any],
    rows: List[Dict[str, Any]],
) -> str:
    """v0.5.180 (re-audit H-RE-3): latency-flavoured headline.
    Mirrors the BW headline's shape — same green callout box,
    same `<span class='num'>` styling — so the report's visual
    rhythm is uniform across BW and lat runs. The unit just
    swaps from Gbps/Mpps to µs avg / µs p99.

    Line-rate efficiency calc is SKIPPED for lat runs: a `% of
    line rate` number against a latency µs value is meaningless
    (lat tests intentionally don't fill the wire)."""
    # v0.5.182 NB-3: surface "X of N workers" honesty when a
    # multi-worker lat run had partial reporting (operator's srv06
    # send_lat showed 1 of 16 workers done; tail used to say
    # `final` masking the gap).
    mode = summary.get("aggregation_mode") or ""
    if mode == "sum_pairs":
        attempted = summary.get("pairs_attempted")
        unit = "pairs"
    else:
        attempted = summary.get("workers_attempted")
        unit = "workers"
    if (isinstance(summary.get("lat_avg_us"), (int, float))
            and summary.get("samples", 0) > 1):
        avg_us = float(summary["lat_avg_us"])
        n = int(summary["samples"])
        if (isinstance(attempted, int) and attempted
                and n < attempted):
            tail = f"average across {n} of {attempted} {unit}"
        else:
            tail = f"average across {n} samples"
    else:
        lats = [r["lat_avg_us"] for r in rows
                if isinstance(r.get("lat_avg_us"), (int, float))]
        avg_us = lats[-1] if lats else None
        if (isinstance(attempted, int) and attempted
                and len(lats) < attempted):
            tail = f"{len(lats)} of {attempted} {unit} reported"
        else:
            tail = "final"
    p99_rows = [r.get("lat_p99_us") for r in rows
                if isinstance(r.get("lat_p99_us"), (int, float))]
    p99_us = p99_rows[-1] if p99_rows else None
    if avg_us is None and p99_us is None:
        return ""
    avg_txt = (f"{avg_us:.2f}" if isinstance(avg_us, float)
               else "—")
    p99_txt = (f"{p99_us:.2f}" if isinstance(p99_us, float)
               else "—")
    extras = []
    if (isinstance(summary.get("lat_min_us"), (int, float))
            and isinstance(summary.get("lat_max_us"), (int, float))
            and summary.get("samples", 0) > 1):
        extras.append(
            f"min {summary['lat_min_us']:.2f} / "
            f"max {summary['lat_max_us']:.2f} µs")
    tail_html = escape(tail)
    if extras:
        tail_html += (" &middot; "
                      + " &middot; ".join(escape(b) for b in extras))
    return (
        f"<div class='headline'>"
        f"<span class='num'>{avg_txt}</span>"
        f"<span class='unit'> µs avg</span>"
        f"<span class='sep'>|</span>"
        f"<span class='num mr'>{p99_txt}</span>"
        f"<span class='unit'> µs p99</span>"
        f"<span class='tail'>&middot; {tail_html}</span>"
        f"</div>"
    )


def _render_params(params: Dict[str, Any]) -> str:
    """v0.5.167: paired-row table instead of dl/dt/dd grid.

    The old `display: grid; grid-template-columns: auto-fill` over
    dt/dd treated each <dt> and <dd> as an independent cell, so
    labels and values interleaved when the column count didn't
    line up. A <table> with one row per pair eliminates the bug
    and keeps the report readable on narrow viewports."""
    if not params:
        return "<p class='meta'>—</p>"
    rows = []
    for k, v in params.items():
        label = _PARAM_LABELS.get(str(k), str(k))
        v_str = _format_param_value(k, v)
        rows.append(
            f"<tr><td class='k'>{escape(label)}</td>"
            f"<td class='v'>{escape(v_str)}</td></tr>"
        )
    return f"<table class='params'><tbody>{''.join(rows)}</tbody></table>"


def _format_param_value(key: str, value: Any) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    unit = _PARAM_UNITS.get(str(key), "")
    return f"{value}{(' ' + unit) if unit else ''}"


