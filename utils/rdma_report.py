        legend += (
            f"<line x1='{legend_x}' y1='4' x2='{legend_x + 14}' "
            f"y2='4' stroke='#b45309' stroke-width='1.5' "
            f"stroke-dasharray='4,3'/>"
            f"<text x='{legend_x + 18}' y='8'>p99</text>"
        )
